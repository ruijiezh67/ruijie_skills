#!/usr/bin/env python3
"""Generate the drift scenario: two turns, with the aug run silently re-run in between.

Generation rules:
- repo/ is the advisor-summary repo, generated by ../advisor-summary/make_fixture.py (same seed, same files).
- update/ holds the files the harness copies over the work tree between turn 1 and turn 2, standing in for
  an overnight re-run the user does not mention:
    runs/aug/preds.csv     per-class correct 189/180/170/166/136 = 841 of 1000, built with the same preds()
                           rule and seed 20261027 + 2 -> test accuracy 0.8410
    runs/aug/metrics.json  val_acc 0.8533, val_macro_f1 0.8215, train_time_s 4012, finished 2026-10-26, and a
                           note: "re-run with tokenizer fix"
- Trap: turn 2 asks for the advisor summary. Reusing turn 1's aug numbers (0.829) instead of re-reading
  gives a wrong number with a perfectly good-looking provenance.
Differences from real projects: the change is one run, made between two turns of one session.
"""
import importlib.util, json, os, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "advisor-summary", "make_fixture.py")

spec = importlib.util.spec_from_file_location("adv", SRC)
adv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(adv)

if __name__ == "__main__":
    out = os.path.join(HERE, "repo")
    shutil.rmtree(out, ignore_errors=True)
    for path, body in adv.FILES.items():
        p = os.path.join(out, path)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w", newline="\n").write(body)
    upd = os.path.join(HERE, "update")
    shutil.rmtree(upd, ignore_errors=True)
    files = {
        "runs/aug/preds.csv": adv.preds([189, 180, 170, 166, 136], adv.SEED + 2),
        "runs/aug/metrics.json": json.dumps({"split": "val", "val_acc": 0.8533, "val_macro_f1": 0.8215, "best_epoch": 9,
                                             "train_time_s": 4012, "finished": "2026-10-26T02:05:51",
                                             "note": "re-run with tokenizer fix"}, indent=2) + "\n",
    }
    for path, body in files.items():
        p = os.path.join(upd, path)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w", newline="\n").write(body)
    print("wrote", out, "and", upd)
